# Implement forward propagation and backpropagation using TensorFlow/Keras. Analyze the
#effect of different learning rates and the number of epochs on model performance.

import numpy as np
import pandas as pd

import matplotlib.pyplot as plt
import seaborn as sns

#wine dataset
from sklearn.datasets import load_wine

from sklearn.model_selection import train_test_split

from sklearn.preprocessing import StandardScaler

from sklearn.metrics import (
    confusion_matrix,
    classification_report,
    accuracy_score
)

import tensorflow as tf

from tensorflow.keras.models import Sequential

from tensorflow.keras.layers import Dense

from tensorflow.keras.optimizers import Adam

import warnings
warnings.filterwarnings("ignore")

print("Libraries Imported Successfully!")

wine = load_wine()

X = wine.data

y = wine.target

print("Wine Dataset Loaded Successfully!")

df = pd.DataFrame(
    X,
    columns=wine.feature_names
)

df["Wine Class"] = y

print("First 5 Rows of Dataset")

df.head()

print("Shape of Dataset")
print(df.shape)

print("\n")

print("Column Names")

print(df.columns)

print("\n")

print("Dataset Information")

df.info()

df.describe()

print("Missing Values")

print(df.isnull().sum())

print("\n")

print("Duplicate Rows")

print(df.duplicated().sum())

plt.figure(figsize=(7,5))

sns.countplot(
    x="Wine Class",
    data=df
)

plt.title("Distribution of Wine Classes")

plt.xlabel("Wine Class")

plt.ylabel("Count")

plt.show()

df.hist(
    figsize=(16,12),
    bins=15,
    edgecolor='black'
)

plt.suptitle("Distribution of Wine Dataset Features")

plt.show()

plt.figure(figsize=(15,6))

sns.boxplot(data=df.iloc[:, :-1])

plt.xticks(rotation=90)

plt.title("Box Plot of Wine Features")

plt.show()

plt.figure(figsize=(12,10))

corr = df.iloc[:, :-1].corr()

sns.heatmap(
    corr,
    annot=True,
    cmap="coolwarm",
    linewidths=0.5
)

plt.title("Correlation Heatmap")

plt.show()

# Features
X = df.drop("Wine Class", axis=1)

# Target
y = df["Wine Class"]

print("Features Shape :", X.shape)
print("Target Shape   :", y.shape)

X_train, X_test, y_train, y_test = train_test_split(
    X,
    y,
    test_size=0.20,
    random_state=42,
    stratify=y
)

print("Training Samples :", X_train.shape[0])
print("Testing Samples  :", X_test.shape[0])

scaler = StandardScaler()

X_train = scaler.fit_transform(X_train)

X_test = scaler.transform(X_test)

print("Feature Scaling Completed!")

#neural network
model = Sequential()

# Input Layer + Hidden Layer 1
model.add(
    Dense(
        units=32,
        activation="relu",
        input_shape=(13,)
    )
)

# Hidden Layer 2
model.add(
    Dense(
        units=16,
        activation="relu"
    )
)

# Output Layer
model.add(
    Dense(
        units=3,
        activation="softmax"
    )
)

print("Neural Network Created Successfully!")

model.summary()

#model compile
model.compile(
    optimizer=Adam(learning_rate=0.001),
    loss="sparse_categorical_crossentropy",
    metrics=["accuracy"]
)

print("Model Compiled Successfully!")

#train model
history = model.fit(
    X_train,
    y_train,
    epochs=50,
    batch_size=16,
    validation_split=0.20,
    verbose=1
)

#training and validation accuracy graph
plt.figure(figsize=(8,5))

plt.plot(history.history['accuracy'], label='Training Accuracy', linewidth=2)
plt.plot(history.history['val_accuracy'], label='Validation Accuracy', linewidth=2)

plt.title("Training vs Validation Accuracy")
plt.xlabel("Epoch")
plt.ylabel("Accuracy")
plt.legend()
plt.grid(True)

plt.show()

#training and validation loss graph
plt.figure(figsize=(8,5))

plt.plot(history.history['loss'], label='Training Loss', linewidth=2)
plt.plot(history.history['val_loss'], label='Validation Loss', linewidth=2)

plt.title("Training vs Validation Loss")
plt.xlabel("Epoch")
plt.ylabel("Loss")
plt.legend()
plt.grid(True)

plt.show()

#model evaluation

test_loss, test_accuracy = model.evaluate(X_test, y_test, verbose=0)

print("Test Loss :", round(test_loss,4))
print("Test Accuracy :", round(test_accuracy*100,2), "%")

#predictions

y_pred_prob = model.predict(X_test)

y_pred = np.argmax(y_pred_prob, axis=1)

print("Predictions Completed Successfully!")

#confusion matrix

cm = confusion_matrix(y_test, y_pred)

plt.figure(figsize=(6,5))

sns.heatmap(
    cm,
    annot=True,
    fmt="d",
    cmap="Blues",
    xticklabels=wine.target_names,
    yticklabels=wine.target_names
)

plt.xlabel("Predicted")
plt.ylabel("Actual")
plt.title("Confusion Matrix")

plt.show()

#classification report

print(classification_report(
    y_test,
    y_pred,
    target_names=wine.target_names
))

#learning rate comparison

learning_rates = [0.1, 0.01, 0.001]

accuracies = []

for lr in learning_rates:

    temp_model = Sequential([
        Dense(32, activation='relu', input_shape=(13,)),
        Dense(16, activation='relu'),
        Dense(3, activation='softmax')
    ])

    temp_model.compile(
        optimizer=Adam(learning_rate=lr),
        loss='sparse_categorical_crossentropy',
        metrics=['accuracy']
    )

    temp_model.fit(
        X_train,
        y_train,
        epochs=50,
        batch_size=16,
        verbose=0
    )

    loss, acc = temp_model.evaluate(
        X_test,
        y_test,
        verbose=0
    )

    accuracies.append(acc*100)

comparison_df = pd.DataFrame({
    "Learning Rate": learning_rates,
    "Accuracy (%)": accuracies
})

comparison_df

#Learning rate vs accuracy graph

plt.figure(figsize=(10,6))

# Different colors for bars
colors = ['#FF6B6B', '#4ECDC4', '#45B7D1']

bars = plt.bar(
    [str(lr) for lr in learning_rates],
    accuracies,
    color=colors,
    edgecolor='black',
    linewidth=1.5,
    width=0.55
)

# Show accuracy value above each bar
for bar, acc in zip(bars, accuracies):
    plt.text(
        bar.get_x() + bar.get_width()/2,
        acc + 0.3,
        f"{acc:.2f}%",
        ha='center',
        fontsize=11,
        fontweight='bold'
    )

plt.title(
    "Effect of Learning Rate on Model Accuracy",
    fontsize=16,
    fontweight='bold'
)

plt.xlabel(
    "Learning Rate",
    fontsize=13,
    fontweight='bold'
)

plt.ylabel(
    "Accuracy (%)",
    fontsize=13,
    fontweight='bold'
)

plt.ylim(min(accuracies)-2, 100)

plt.grid(axis='y', linestyle='--', alpha=0.6)

plt.tight_layout()

plt.show()

#epoch comparison

epochs_list = [20,50,100]

epoch_accuracy = []

for ep in epochs_list:

    temp_model = Sequential([
        Dense(32, activation='relu', input_shape=(13,)),
        Dense(16, activation='relu'),
        Dense(3, activation='softmax')
    ])

    temp_model.compile(
        optimizer=Adam(learning_rate=0.001),
        loss='sparse_categorical_crossentropy',
        metrics=['accuracy']
    )

    temp_model.fit(
        X_train,
        y_train,
        epochs=ep,
        batch_size=16,
        verbose=0
    )

    loss, acc = temp_model.evaluate(
        X_test,
        y_test,
        verbose=0
    )

    epoch_accuracy.append(acc*100)

epoch_df = pd.DataFrame({
    "Epochs": epochs_list,
    "Accuracy (%)": epoch_accuracy
})

epoch_df

#epoch comparison graph

plt.figure(figsize=(7,5))

plt.plot(
    epochs_list,
    epoch_accuracy,
    marker='o',
    linewidth=2
)

plt.title("Epochs vs Accuracy")

plt.xlabel("Epochs")

plt.ylabel("Accuracy (%)")

plt.grid(True)

plt.show()

#predict new sample

sample = [[13.2,2.7,2.5,18.5,100,2.5,2.8,0.3,1.8,5.2,1.0,3.0,800]]

sample = scaler.transform(sample)

prediction = model.predict(sample)

predicted_class = np.argmax(prediction)

print("Predicted Wine Class :", predicted_class)